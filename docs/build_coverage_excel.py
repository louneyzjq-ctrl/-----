def fill(hex_color: str) -> PatternFill:
    return PatternFill("solid", fgColor=hex_color)


def font(bold=False, size=11, color=WHITE, name="Calibri") -> Font:
    return Font(name=name, bold=bold, size=size, color=color)


def align(h="left", v="center", wrap=True) -> Alignment:
    return Alignment(horizontal=h, vertical=v, wrap_text=wrap)


def set_widths(ws, widths: dict[str, float]) -> None:
    for col, width in widths.items():
        ws.column_dimensions[col].width = width


def style_header_row(ws, row: int, cols: int, color: str = NAVY) -> None:
    for col in range(1, cols + 1):
        cell = ws.cell(row, col)
        cell.fill = fill(color)
        cell.font = font(bold=True, size=11, color=WHITE)
        cell.alignment = align("center", "center")
        cell.border = thin


def style_body(ws, start_row: int, end_row: int, cols: int, zebra: str | None = LIGHT2) -> None:
    for r in range(start_row, end_row + 1):
        for c in range(1, cols + 1):
            cell = ws.cell(r, c)
            cell.font = font(size=10, color=BLACK)
            cell.alignment = align("left" if c > 1 else "center", "center")
            cell.border = thin
            if zebra and (r - start_row) % 2 == 1:
                if not cell.fill or cell.fill.fgColor is None or cell.fill.fgColor.rgb in ("00000000", "0"):
                    cell.fill = fill(zebra)


def title_block(ws, title: str, subtitle: str, cols: int) -> None:
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=cols)
    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=cols)
    a1 = ws.cell(1, 1, title)
    a1.fill = fill(NAVY)
    a1.font = font(bold=True, size=16, color=WHITE)
    a1.alignment = align("left", "center")
    a2 = ws.cell(2, 1, subtitle)
    a2.fill = fill(NAVY2)
    a2.font = font(bold=False, size=11, color="F5E6B8")
    a2.alignment = align("left", "center")
    ws.row_dimensions[1].height = 28
    ws.row_dimensions[2].height = 22
    for c in range(1, cols + 1):
        ws.cell(1, c).fill = fill(NAVY)
        ws.cell(2, c).fill = fill(NAVY2)


def paint_row(ws, row: int, cols: int, color: str) -> None:
    for c in range(1, cols + 1):
        ws.cell(row, c).fill = fill(color)


